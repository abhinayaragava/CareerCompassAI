def recommend_after12th_exams(
    career_domain,
    stream,
    exam_interest,
    strongest_subjects=None,
    career_direction=None
):
    """Return personalized competitive exam guidance for an After 12th student."""

    if not exam_interest or exam_interest.strip().lower() == "no":
        return []

    domain_exams = AFTER_12TH_COMPETITIVE_EXAMS.get(career_domain, [])

    if not domain_exams:
        return []

    stream_normalized = (stream or "").strip().lower()

    strongest_subjects = strongest_subjects or ""

    student_subjects = {
        subject.strip().lower()
        for subject in strongest_subjects.split(",")
        if subject.strip()
    }

    career_direction_normalized = (
        (career_direction or "").strip().lower()
    )

    results = []

    for exam_data in domain_exams:

        allowed_streams = [
            s.lower()
            for s in exam_data.get("streams", [])
        ]

        stream_match = (
            not stream_normalized
            or any(
                s in stream_normalized
                or stream_normalized in s
                for s in allowed_streams
            )
        )

        if not stream_match:
            continue

        exam_subjects = {
            subject.strip().lower()
            for subject in exam_data.get("subjects", [])
        }

        subject_matches = []

        for subject in exam_subjects:
            if subject in student_subjects:
                subject_matches.append(subject)

        personalized_exam = exam_data.copy()

        personalized_exam["subject_matches"] = subject_matches

        personalized_exam["relevance"] = (
            "This exam matches your selected career domain and "
            "12th stream."
        )

        if subject_matches:
            personalized_exam["relevance"] += (
                f" Your strongest subjects include "
                f"{', '.join(subject_matches)}."
            )

        if career_direction_normalized:
            personalized_exam["relevance"] += (
                f" It also supports your preferred career direction: "
                f"{career_direction}."
            )

        results.append(personalized_exam)

    return results








